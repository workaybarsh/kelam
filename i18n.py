_current = DEFAULT_LANG


def get_lang() -> str:
    return _current


def set_lang(code: str) -> str:
    global _current
    code = (code or DEFAULT_LANG).lower()
    _current = code if code in LANGUAGES else DEFAULT_LANG
    return _current


def toggle_lang() -> str:
    return set_lang("tr" if _current == "en" else "en")


def tr(text: str) -> str:
    """Translate an English UI string; unknown strings pass through unchanged."""
    if _current == "tr":
        return TR.get(text, text)
    return text
